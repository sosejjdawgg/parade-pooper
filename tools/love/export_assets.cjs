// Exports the browser game's own art and sound for the LÖVE (handheld) port, so both versions
// share identical pixels and sound effects:
//   handheld/love/assets/atlas.png + atlas.lua   every sprite, the HUD faces
//   handheld/love/assets/sfx/*.wav               each sound effect, rendered offline
//   handheld/love/assets/music/menu.wav          the menu chiptune, one seamless loop
// Usage: node tools/love/export_assets.cjs   (after `node tools/bundle.cjs`)
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..', '..'), out = path.join(root, 'handheld', 'love', 'assets');
(async () => {
  const b = await chromium.launch(), pg = await b.newPage();
  const errs = []; pg.on('pageerror', (e) => errs.push(String(e)));
  await pg.goto('file://' + path.join(root, 'vape-kayak.html')); await pg.waitForTimeout(600);

  // ---- sprite atlas (shelf packed) ----
  const atlas = await pg.evaluate(() => {
    const { SPR, face } = __vc, items = [];
    const add = (name, c) => items.push({ name, c });
    SPR.kayak.forEach((c, i) => add('kayak' + i, c));
    SPR.vape.forEach((c, i) => add('vape' + i, c));
    SPR.bigVape.forEach((c, i) => add('bigVape' + i, c));
    for (const k of [70, 90, 110]) add('barge' + k, SPR.barge[k]);
    SPR.sandbar.forEach((c, i) => add('sandbar' + i, c));
    SPR.signs.forEach((c, i) => add('sign' + i, c));
    for (const k of ['pier', 'cash', 'tea', 'swan', 'pap', 'tumble', 'piranha', 'mozzie', 'croc', 'trolley', 'barrel', 'cone', 'cactus', 'palm', 'lamp', 'bollard']) add(k, SPR[k]);
    for (let t = 0; t <= 4; t++) for (const m of ['c', 'l', 'r', 'ouch', 'grin', 'drag', 'puff', 'dead']) add('face' + t + m, face(t, m));
    items.sort((a, b) => b.c.height - a.c.height);
    const W = 512, cv = document.createElement('canvas'); cv.width = W; cv.height = 1024;
    const g = cv.getContext('2d'); let x = 1, y = 1, rowH = 0; const rects = {};
    for (const it of items) {
      if (x + it.c.width + 1 > W) { x = 1; y += rowH + 1; rowH = 0; }
      g.drawImage(it.c, x, y); rects[it.name] = [x, y, it.c.width, it.c.height];
      x += it.c.width + 1; rowH = Math.max(rowH, it.c.height);
    }
    g.fillStyle = '#fff'; g.fillRect(W - 2, 1022, 1, 1); rects.white = [W - 2, 1022, 1, 1];
    return { png: cv.toDataURL('image/png').split(',')[1], rects, h: y + rowH + 2 };
  });
  fs.writeFileSync(path.join(out, 'atlas.png'), Buffer.from(atlas.png, 'base64'));
  let lua = '-- generated by tools/love/export_assets.cjs from the browser game: { x, y, w, h } in atlas.png\nreturn {\n';
  for (const [k, r] of Object.entries(atlas.rects)) lua += `  ['${k}'] = { ${r.join(', ')} },\n`;
  fs.writeFileSync(path.join(out, 'atlas.lua'), lua + '}\n');

  // ---- sound effects + menu chiptune, rendered with the same Web Audio code ----
  const sounds = await pg.evaluate(async () => {
    const SR = 44100, outs = {};
    const wav = (buf) => {
      const d = buf.getChannelData(0), n = d.length, ab = new ArrayBuffer(44 + n * 2), v = new DataView(ab);
      const str = (o, s) => { for (let i = 0; i < s.length; i++) v.setUint8(o + i, s.charCodeAt(i)); };
      str(0, 'RIFF'); v.setUint32(4, 36 + n * 2, true); str(8, 'WAVE'); str(12, 'fmt '); v.setUint32(16, 16, true);
      v.setUint16(20, 1, true); v.setUint16(22, 1, true); v.setUint32(24, SR, true); v.setUint32(28, SR * 2, true); v.setUint16(32, 2, true); v.setUint16(34, 16, true);
      str(36, 'data'); v.setUint32(40, n * 2, true);
      for (let i = 0; i < n; i++) v.setInt16(44 + i * 2, Math.max(-1, Math.min(1, d[i])) * 32767, true);
      let s = ''; const u = new Uint8Array(ab); for (let i = 0; i < u.length; i += 0x8000) s += String.fromCharCode.apply(null, u.subarray(i, i + 0x8000));
      return btoa(s);
    };
    async function render(len, fn) {
      const ac = new OfflineAudioContext(1, Math.ceil(len * SR), SR);
      const noise = ac.createBuffer(1, SR * 0.5, SR); const nd = noise.getChannelData(0); for (let i = 0; i < nd.length; i++) nd[i] = Math.random() * 2 - 1;
      const tone = (freq, dur, vol = 0.06, type = 'square', slide = 0, delay = 0) => {
        const t = delay, o = ac.createOscillator(), g = ac.createGain();
        o.type = type; o.frequency.setValueAtTime(freq, t);
        if (slide) o.frequency.exponentialRampToValueAtTime(Math.max(30, freq * slide), t + dur);
        g.gain.setValueAtTime(vol, t); g.gain.exponentialRampToValueAtTime(0.0001, t + dur);
        o.connect(g).connect(ac.destination); o.start(t); o.stop(t + dur + 0.02);
      };
      const hiss = (dur, vol = 0.05, delay = 0) => {
        const t = delay, s = ac.createBufferSource(), g = ac.createGain();
        s.buffer = noise; g.gain.setValueAtTime(vol, t); g.gain.exponentialRampToValueAtTime(0.0001, t + dur);
        s.connect(g).connect(ac.destination); s.start(t); s.stop(t + dur + 0.02);
      };
      fn(tone, hiss, ac);
      return ac.startRendering();
    }
    // the exact definitions from src/platform.js (sfx)
    const defs = {
      big: (t, h) => { t(660, 0.08, 0.06); t(990, 0.12, 0.06, 'square', 0, 0.07); },
      cash: (t, h) => { t(1320, 0.05, 0.05); t(1760, 0.1, 0.05, 'square', 0, 0.05); },
      puff: (t, h) => h(0.08, 0.012),
      nova: (t, h) => { h(0.4, 0.07); t(110, 0.4, 0.07, 'triangle', 0.4); },
      kill: (t, h) => { h(0.05, 0.035); t(200, 0.05, 0.03, 'square', 0.5); },
      heal: (t, h) => [392, 523, 659].forEach((f, i) => t(f, 0.14, 0.07, 'triangle', 0, i * 0.08)),
      hurt: (t, h) => { t(160, 0.25, 0.1, 'sawtooth', 0.4); h(0.2, 0.08); },
      level: (t, h) => [523, 659, 784, 1047].forEach((f, i) => t(f, 0.12, 0.06, 'square', 0, i * 0.07)),
      pick: (t, h) => { t(784, 0.06, 0.06); t(1175, 0.14, 0.06, 'square', 0, 0.06); },
      ui: (t, h) => t(440, 0.04, 0.04),
      no: (t, h) => t(140, 0.12, 0.06),
      buy: (t, h) => [659, 880, 1319].forEach((f, i) => t(f, 0.1, 0.06, 'square', 0, i * 0.06)),
      death: (t, h) => { t(300, 0.9, 0.12, 'sawtooth', 0.1); h(0.7, 0.12); },
    };
    for (let c = 0; c <= 14; c++) defs['vape' + c] = (t) => t(520 * Math.pow(2, Math.min(c, 14) / 12), 0.07, 0.05);
    for (const k in defs) outs[k] = wav(await render(1.0, defs[k]));
    // menu chiptune (src/music.js), 8 bars; the tail that rings past the loop end is folded back onto the start
    const BPM = 124, six = 60 / BPM / 4, loopLen = 128 * six;
    const N = { A: 9, 'A#': 10, B: 11, C: 0, 'C#': 1, D: 2, 'D#': 3, E: 4, F: 5, 'F#': 6, G: 7, 'G#': 8 };
    const hz = (n) => { const m = /^([A-G]#?)(\d)$/.exec(n); return 440 * Math.pow(2, (N[m[1]] - 9) / 12 + (+m[2] - 4)); };
    const CH = [{ bass: 'A2', arp: ['A4', 'C5', 'E5', 'C5'] }, { bass: 'F2', arp: ['A4', 'C5', 'F5', 'C5'] }, { bass: 'G2', arp: ['B4', 'D5', 'G5', 'D5'] }, { bass: 'E2', arp: ['B4', 'E5', 'G#5', 'E5'] }];
    const LEAD = [[['E5', 1], ['A5', 1], ['G5', 0.5], ['E5', 0.5], ['C5', 1]], [['D5', 0.5], ['C5', 0.5], ['A4', 1], ['C5', 1], ['F5', 1]], [['G5', 1.5], ['F5', 0.5], ['D5', 1], ['B4', 1]], [['E5', 1], ['G#5', 1], ['B5', 1], ['G#5', 0.5], ['E5', 0.5]],
      [['A5', 1], ['C6', 1], ['B5', 0.5], ['A5', 0.5], ['E5', 1]], [['F5', 0.5], ['A5', 0.5], ['C6', 1], ['A5', 1], ['F5', 1]], [['G5', 1], ['B5', 1], ['D6', 1], ['B5', 0.5], ['G5', 0.5]], [['G#5', 0.5], ['F5', 0.5], ['E5', 0.5], ['D5', 0.5], ['B4', 1], ['E5', 1]]];
    const lead = {}; LEAD.forEach((bar, bi) => { let pos = 0; for (const [n, len] of bar) { lead[bi * 16 + Math.round(pos * 4)] = [n, len]; pos += len; } });
    const menu = await render(loopLen + 1, (t, h, ac) => {
      const hat = ac.createBuffer(1, 2205, 44100); const hd = hat.getChannelData(0); for (let i = 0; i < hd.length; i++) hd[i] = (Math.random() * 2 - 1) * (1 - i / hd.length);
      const voice = (type, freq, at, dur, vol) => { const o = ac.createOscillator(), g = ac.createGain(); o.type = type; o.frequency.value = freq;
        g.gain.setValueAtTime(vol, at); g.gain.setValueAtTime(vol * 0.7, at + dur * 0.5); g.gain.linearRampToValueAtTime(0.0001, at + dur); o.connect(g).connect(ac.destination); o.start(at); o.stop(at + dur + 0.02); };
      for (let s = 0; s < 128; s++) {
        const bar = (s >> 4) & 7, in16 = s & 15, ch = CH[bar & 3], at = s * six;
        voice('square', hz(ch.arp[in16 & 3]), at, six * 0.9, 0.035);
        if ((in16 & 1) === 0) voice('triangle', hz(ch.bass) * ((in16 & 7) === 6 ? 2 : 1), at, six * 1.8, 0.16);
        if (lead[s]) voice('square', hz(lead[s][0]), at, lead[s][1] * six * 4 * 0.92, 0.07);
        const src = ac.createBufferSource(), g = ac.createGain(); src.buffer = hat; g.gain.value = (in16 & 3) === 2 ? 0.05 : (in16 & 3) === 0 ? 0.02 : 0;
        if (g.gain.value) { src.connect(g).connect(ac.destination); src.start(at); }
      }
    });
    const d = menu.getChannelData(0), L = Math.round(loopLen * 44100), loop = new AudioBuffer({ length: L, sampleRate: 44100 }), ld = loop.getChannelData(0);
    for (let i = 0; i < L; i++) ld[i] = d[i] + (i + L < d.length ? d[i + L] : 0);
    outs.menu = wav(loop);
    return outs;
  });
  for (const [k, b64] of Object.entries(sounds)) fs.writeFileSync(path.join(out, k === 'menu' ? 'music' : 'sfx', k + '.wav'), Buffer.from(b64, 'base64'));
  console.log('atlas', Object.keys(atlas.rects).length, 'sprites, height', atlas.h, '| sounds', Object.keys(sounds).length, '| errors', errs);
  await b.close();
})();
